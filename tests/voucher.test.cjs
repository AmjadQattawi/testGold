const fs = require('fs');
const path = require('path');
const assert = require('node:assert/strict');
const ts = require('typescript');
const source = fs.readFileSync(path.resolve(__dirname, '../src/utils/voucher.ts'), 'utf8');
const code = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
const mod = { exports: {} };
const formatModule = { exports: {} };
const formatCode = ts.transpileModule(fs.readFileSync(path.resolve(__dirname, '../src/utils/numberFormat.ts'), 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
new Function('module','exports',formatCode)(formatModule,formatModule.exports);
new Function('module', 'exports', 'require', code)(mod, mod.exports, () => formatModule.exports);
const { blankLine, newVoucher, voucherTotals, formatAmount, updateVoucherLine, localDate, voucherLineError, deleteVoucherLines } = mod.exports;
const rows = [{ ...blankLine(1), debit: '0.1000' }, { ...blankLine(2), debit: '0.2000' }, { ...blankLine(3), credit: '0.3000' }];
assert.deepEqual(voucherTotals(rows), { debit: 3000, credit: 3000, difference: 0, balanced: true });
assert.equal(formatAmount(voucherTotals(rows).debit), '0.3000');
assert.equal(voucherTotals([]).balanced, false);
assert.equal(voucherTotals([{ ...blankLine(1), debit: '5.0000', rate: '2.0000' }]).debit, 100000);
assert.equal(voucherTotals([{ ...blankLine(1), debit: '3.0000' }, { ...blankLine(2), credit: '1.0000' }]).difference, 20000);
const draft = newVoucher();
assert.equal(draft.rows.length, 1);
assert.equal(new Set(draft.rows.map(row => row.id)).size, 1);
assert.equal(draft.number, '');
assert.equal(draft.rows[0].rate, '1');
assert.equal(draft.rows[0].currency, 'JOD');
assert.equal(draft.date, localDate());
assert.equal(draft.rows[0].dueDate, localDate());
console.log('Passed voucher totals: decimal balance, exchange rate, difference, empty totals and new draft defaults.');

let editing = [blankLine(1)];
editing = updateVoucherLine(editing, editing[0].id, 'account', 'cash');
assert.equal(editing.length, 1);
editing = updateVoucherLine(editing, editing[0].id, 'debit', '100');
assert.equal(editing.length, 2);
assert.equal(editing[1].lineNo, '02');
editing = updateVoucherLine(editing, editing[0].id, 'description', 'Edited');
assert.equal(editing.length, 2);
editing = updateVoucherLine(editing, editing[1].id, 'credit', '100');
assert.equal(editing.length, 2);
editing = updateVoucherLine(editing, editing[1].id, 'account', 'bank');
assert.equal(editing.length, 3);
assert.equal(voucherTotals(editing).balanced, true);
console.log('Passed automatic rows: complete last row appends once; incomplete and existing rows do not append.');

let conflicted = [{ ...blankLine(1), account: 'cash', debit: '100', credit: '50' }, blankLine(2)];
const unchanged = updateVoucherLine(conflicted, conflicted[1].id, 'account', 'bank');
assert.equal(unchanged, conflicted);
const stillBlocked = updateVoucherLine(conflicted, conflicted[0].id, 'description', 'Fixing');
assert.equal(stillBlocked.length, 2);
const corrected = updateVoucherLine(stillBlocked, stillBlocked[0].id, 'credit', '0');
assert.equal(updateVoucherLine(corrected, corrected[1].id, 'account', 'bank')[1].account, 'bank');
let lastConflict = [{ ...blankLine(1), account: 'cash', debit: '100', credit: '50' }];
assert.equal(updateVoucherLine(lastConflict, lastConflict[0].id, 'account', 'cash').length, 1);
assert.equal(updateVoucherLine(lastConflict, lastConflict[0].id, 'credit', '').length, 2);
console.log('Passed conflict guard: block other rows and auto-append until debit/credit conflict is corrected.');

const missingAccount = { ...blankLine(1), debit: '50' };
assert.equal(voucherLineError(missingAccount), 'voucherAccountRequired');
assert.equal(voucherLineError(blankLine(1)), null);
const missingRows = [missingAccount, blankLine(2)];
assert.equal(updateVoucherLine(missingRows, missingRows[1].id, 'account', 'bank'), missingRows);
const resolvedAccount = updateVoucherLine(missingRows, missingAccount.id, 'account', 'cash');
assert.equal(voucherLineError(resolvedAccount[0]), null);
console.log('Passed inline account validation: empty untouched row accepted; amount without account blocks other rows until selection.');

assert.equal(formatAmount(12345670000), '1,234,567.0000');
assert.equal(formatModule.exports.formatDecimal('1234.5'), '1,234.5000');
assert.equal(formatModule.exports.normalizeDecimal('1,234,567.1234'), '1234567.1234');
assert.equal(formatModule.exports.normalizeDecimal('١٬٢٣٤٫٥'), '1234.5');
assert.equal(formatModule.exports.normalizeDecimal('1.12345'), null);
console.log('Passed numeric formatting: thousands, millions, four decimal places, Arabic input and decimal limit.');

const deletionRows=[{...blankLine(1),account:'cash',debit:'100'},{...blankLine(2),account:'bank',credit:'100'},blankLine(3)];
const afterDelete=deleteVoucherLines(deletionRows,[deletionRows[0].id,deletionRows[2].id]);
assert.equal(afterDelete.length,1);assert.equal(afterDelete[0].id,deletionRows[1].id);assert.equal(afterDelete[0].lineNo,'01');
const emptyReset=deleteVoucherLines(deletionRows,deletionRows.map(row=>row.id));assert.equal(emptyReset.length,1);assert.equal(emptyReset[0].account,'');
assert.equal(deleteVoucherLines(missingRows,[missingRows[0].id]),missingRows);
console.log('Passed multi-delete: selected rows only, renumbering, keep an empty row and block deletion with validation errors.');
