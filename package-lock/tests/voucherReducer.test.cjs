const fs=require('fs');
const path=require('path');
const assert=require('node:assert/strict');
const ts=require('typescript');
const cache=new Map();
let uuidCalls=0;
function load(file){
 file=path.normalize(file);if(cache.has(file))return cache.get(file);
 const source=fs.readFileSync(path.resolve(__dirname,'../src',file),'utf8');
 const code=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
 const mod={exports:{}};
 new Function('require','module','exports','crypto',code)(name=>load(path.join(path.dirname(file),name+'.ts')),mod,mod.exports,{randomUUID:()=>{uuidCalls++;return 'id-'+uuidCalls;}});
 cache.set(file,mod.exports);return mod.exports;
}
const {voucherReducer,createVoucherState}=load('reducers/voucherReducer.ts');
const {newVoucher,blankLine}=load('utils/voucher.ts');
let state=createVoucherState(newVoucher(),[]);
const initial=structuredClone(state);
state=voucherReducer(state,{type:'fieldChanged',key:'notes',value:'Note'});
assert.equal(initial.draft.notes,'');assert.equal(state.draft.notes,'Note');
const id=state.draft.rows[0].id;
state=voucherReducer(state,{type:'lineChanged',id,key:'debit',value:'100',nextLine:blankLine(2)});
assert.equal(state.draft.rows.length,1);
const blocked=state;
state=voucherReducer(state,{type:'rowsSelected',ids:[id]});assert.equal(state,blocked);
const action={type:'lineChanged',id,key:'account',value:'cash',nextLine:blankLine(2)};
const beforeCalls=uuidCalls;
const once=voucherReducer(state,action);const twice=voucherReducer(state,action);
assert.deepEqual(once,twice);assert.equal(uuidCalls,beforeCalls);assert.equal(once.draft.rows.length,2);
state=voucherReducer(once,{type:'rowsSelected',ids:[id,id,'unknown']});assert.deepEqual(state.selectedIds,[id]);
state=voucherReducer(state,{type:'selectedRowsDeleted',emptyLine:blankLine(1)});
assert.equal(state.draft.rows.length,1);assert.deepEqual(state.selectedIds,[]);assert.equal(state.draft.rows[0].lineNo,'01');
state=voucherReducer(state,{type:'searchToggled'});assert.equal(state.searchOpen,true);
state=voucherReducer(state,{type:'searchChanged',value:'1838'});assert.equal(state.search,'1838');
const stored=structuredClone(state.draft);
state=voucherReducer(state,{type:'draftsPersisted',saved:[stored]});assert.equal(state.saved.length,1);
const another=newVoucher();state=voucherReducer(state,{type:'draftOpened',draft:another});
assert.equal(state.draft.id,another.id);assert.equal(state.searchOpen,false);assert.deepEqual(state.selectedIds,[]);
const immutable=structuredClone(state);voucherReducer(state,{type:'fieldChanged',key:'number',value:'99'});assert.deepEqual(state,immutable);
assert.equal(voucherReducer(state,{type:'lineChanged',id:state.draft.rows[0].id,key:'id',value:'bad',nextLine:blankLine(2)}),state);
console.log('Passed voucher reducer: immutable fields, validation lock, pure automatic rows, multi-selection, deletion, saved drafts, draft switching and search.');
